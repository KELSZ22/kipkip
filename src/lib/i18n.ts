export const MESSAGES: Record<Tone, Messages> = { english, taglish, filipino };

export type MessageParams = Record<string, string | number>;

export function translate(tone: Tone, key: MessageKey, params: MessageParams = {}): string {
  return MESSAGES[tone][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    name in params ? String(params[name]) : placeholder,
  );
}

/** Returns a translator bound to the user's tone that also fills in `{name}` with the companion's name. */
export function useT() {
  const tone = useSettings((state) => state.values.tone);
  const companionName = useSettings((state) => state.values.companion_name);
  return (key: MessageKey, params?: MessageParams) =>
    translate(tone, key, { name: companionName, ...params });
}
